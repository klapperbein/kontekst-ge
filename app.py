@socketio.on('create_room')
def handle_create_room(data):
    username = data.get('username', 'მოთამაშე 1')
    room_id = str(random.randint(1000, 9999))
    target = random.choice(TARGET_WORDS)
    
    rooms[room_id] = {
        'target_word': target,
        'guesses': [],
        'players': [username],
        'is_over': False,
        'max_guesses': 30
    }
    
    join_room(room_id)
    emit('room_created', {
        'room_id': room_id,
        'max_guesses': 30,
        'guesses_count': 0
    })

@socketio.on('join_room')
def handle_join_room(data):
    room_id = data.get('room_id')
    username = data.get('username', 'მოთამაშე 2')

    if room_id not in rooms:
        emit('error_message', {'error': 'ოთახი ვერ მოიძებნა!'})
        return

    room = rooms[room_id]
    if username not in room['players']:
        room['players'].append(username)

    join_room(room_id)
    emit('player_joined', {
        'room_id': room_id,
        'history': room['guesses'],
        'guesses_count': len(room['guesses']),
        'max_guesses': room['max_guesses'],
        'is_over': room['is_over']
    })

@socketio.on('make_guess')
def handle_make_guess(data):
    room_id = data.get('room_id')
    username = data.get('username')
    word = data.get('word', '').strip().lower()

    if room_id not in rooms:
        return

    room = rooms[room_id]
    if room['is_over']:
        return

    target = room['target_word']
    score = get_similarity(word, target)
    is_correct = (word == target)

    guess_entry = {
        'player': username,
        'word': word,
        'score': score
    }
    
    room['guesses'].append(guess_entry)
    guesses_count = len(room['guesses'])

    if is_correct or guesses_count >= room['max_guesses']:
        room['is_over'] = True

    emit('opponent_guessed', {
        'player': username,
        'word': word,
        'score': score,
        'is_correct': is_correct,
        'guesses_count': guesses_count,
        'max_guesses': room['max_guesses'],
        'is_over': room['is_over'],
        'target_word': target if room['is_over'] else None
    }, to=room_id)

@socketio.on('restart_game')
def handle_restart(data):
    room_id = data.get('room_id')
    if room_id in rooms:
        rooms[room_id]['target_word'] = random.choice(TARGET_WORDS)
        rooms[room_id]['guesses'] = []
        rooms[room_id]['is_over'] = False
        emit('game_restarted', {'max_guesses': rooms[room_id]['max_guesses']}, to=room_id)

