def get_similarity(w1, w2):
    if w1 not in word_vectors or w2 not in word_vectors:
        return 0.0
    v1 = word_vectors[w1]
    v2 = word_vectors[w2]
    sim = np.dot(v1, v2)
    score = max(0.0, float(sim)) * 100
    return round(score, 1)

